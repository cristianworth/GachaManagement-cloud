-- Shared America calendar; notification preferences and receipts remain per profile.
begin;

create table public.game_agenda (
    id bigint generated by default as identity primary key,
    game_id bigint not null references public.games(id) on delete cascade,
    kind text not null check (kind in ('maintenance', 'banner')),
    title text not null check (length(btrim(title)) between 1 and 200),
    version text not null default '' check (length(version) <= 80),
    starts_at timestamptz not null check (isfinite(starts_at)),
    ends_at timestamptz not null check (isfinite(ends_at) and ends_at > starts_at),
    source_url text not null default '' check (source_url = '' or source_url ~ '^https://[^[:space:]]+$'),
    image_url text not null default '' check (image_url = '' or image_url ~ '^https://[^[:space:]]+$'),
    timing_note text not null default '' check (length(timing_note) <= 300),
    updated_at timestamptz not null default now(),
    unique (game_id, kind, starts_at, title)
);
alter table public.game_agenda enable row level security;
create policy "shared catalogue agenda" on public.game_agenda for all to anon
    using (exists (select 1 from public.games g where g.id = game_id and g.catalogue_owner is null))
    with check (exists (select 1 from public.games g where g.id = game_id and g.catalogue_owner is null));
grant select, insert, update, delete on public.game_agenda to anon;
grant usage, select on sequence public.game_agenda_id_seq to anon;

create function public.list_game_agenda() returns jsonb
language sql stable security invoker set search_path = public as $$
    select coalesce(jsonb_agg(to_jsonb(a) || jsonb_build_object('game_name', g.description, 'abbreviation', g.abbreviation)
        order by a.starts_at, a.id), '[]')
    from public.game_agenda a join public.games g on g.id = a.game_id;
$$;

create function public.game_agenda_catalogue() returns jsonb
language sql stable security invoker set search_path = public as $$
    select coalesce(jsonb_agg(jsonb_build_object('id', id, 'description', description, 'abbreviation', abbreviation)
        order by description), '[]') from public.games where catalogue_owner is null;
$$;

create function public.save_game_agenda(p_entry jsonb, p_id bigint default null) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare v_row public.game_agenda%rowtype;
begin
    if not exists (select 1 from public.games where id = (p_entry->>'game_id')::bigint and catalogue_owner is null) then
        raise exception 'Escolha um jogo do catálogo compartilhado.';
    end if;
    if p_id is null then
        insert into public.game_agenda (game_id, kind, title, version, starts_at, ends_at, source_url, image_url, timing_note)
        values ((p_entry->>'game_id')::bigint, p_entry->>'kind', btrim(p_entry->>'title'), coalesce(p_entry->>'version', ''),
            (p_entry->>'starts_at')::timestamptz, (p_entry->>'ends_at')::timestamptz,
            coalesce(p_entry->>'source_url', ''), coalesce(p_entry->>'image_url', ''), coalesce(p_entry->>'timing_note', '')) returning * into v_row;
    else
        update public.game_agenda set game_id = (p_entry->>'game_id')::bigint, kind = p_entry->>'kind',
            title = btrim(p_entry->>'title'), version = coalesce(p_entry->>'version', ''),
            starts_at = (p_entry->>'starts_at')::timestamptz, ends_at = (p_entry->>'ends_at')::timestamptz,
            source_url = coalesce(p_entry->>'source_url', ''), image_url = coalesce(p_entry->>'image_url', ''),
            timing_note = coalesce(p_entry->>'timing_note', ''), updated_at = now()
            where id = p_id returning * into v_row;
        if not found then raise exception 'Registro não encontrado. Atualize a agenda.'; end if;
    end if;
    return to_jsonb(v_row);
end $$;

create function public.delete_game_agenda(p_id bigint) returns void
language sql security invoker set search_path = public as $$
    delete from public.game_agenda where id = p_id;
$$;

create or replace function public.list_profile_games(p_profile_id text) returns jsonb
language plpgsql security invoker set search_path = public as $$ begin
    perform public.require_profile(p_profile_id);
    return coalesce((select jsonb_agg(to_jsonb(g) || pg.overrides || jsonb_build_object('game_agenda',
        coalesce((select jsonb_agg(to_jsonb(a) || jsonb_build_object('read', pg.overrides->('agenda_notice_read_' || a.id))
            order by a.starts_at, a.id) from public.game_agenda a where a.game_id = g.id), '[]'::jsonb))
        order by (pg.overrides->>'date_max_stamina') nulls last)
        from public.games g join public.profile_games pg on pg.game_id = g.id
        where pg.profile_id = p_profile_id and pg.enabled), '[]');
end $$;

grant execute on function public.list_game_agenda(), public.game_agenda_catalogue(),
    public.save_game_agenda(jsonb, bigint), public.delete_game_agenda(bigint) to anon;
commit;
