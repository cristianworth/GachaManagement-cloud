import test from 'node:test';
import assert from 'node:assert/strict';
import {createDomHarness,waitFor} from './helpers/domHarness.mjs';

test('shared agenda screen edits global records, preserves failed drafts and filters ended periods',async t=>{
    const {dom,state,close}=createDomHarness(); t.after(close);
    t.mock.method(console,'error',()=>{});
    t.mock.timers.enable({apis:['Date'],now:Date.parse('2026-10-25T12:00:00Z')});
    const {displayGameAgenda}=await import('../js/ui/gameAgenda.js');
    const {selectProfile}=await import('../js/services/profileSession.js');
    const el=id=>document.getElementById(id);
    state.games=[{id:1,description:'Genshin',abbreviation:'GI'},{id:2,description:'Other',abbreviation:'HSR'}];
    state.agenda=[{id:10,game_id:1,kind:'banner',title:'<b>Featured</b>',version:'7.1',starts_at:'2026-10-26T17:00:00Z',ends_at:'2026-11-03T19:59:00Z',source_url:'https://example.org/announcement',image_url:''},
        {id:11,game_id:2,kind:'maintenance',title:'Past update',starts_at:'2026-10-20T22:00:00Z',ends_at:'2026-10-21T03:00:00Z'}];
    document.querySelector('[data-page="gameAgenda"]').style.display='block';
    await displayGameAgenda();
    assert.equal(el('agendaList').children.length,1);
    assert.equal(el('agendaList').querySelector('b'),null,'Titles are rendered as plain text');
    assert.match(el('agendaList').textContent,/26\/10\/2026.*14:00/);
    el('agendaShowEnded').checked=true;el('agendaShowEnded').dispatchEvent(new dom.window.Event('change'));
    assert.equal(el('agendaList').children.length,2);
    el('agendaKindFilter').value='maintenance';el('agendaKindFilter').dispatchEvent(new dom.window.Event('change'));
    assert.equal(el('agendaList').children.length,1);
    assert.match(el('agendaList').textContent,/Past update/);
    el('agendaGameFilter').value='1';el('agendaGameFilter').dispatchEvent(new dom.window.Event('change'));
    assert.equal(el('agendaList').children.length,0,'Game and type filters intersect');
    assert.equal(el('agendaEmpty').hidden,false);
    el('agendaKindFilter').value='banner';el('agendaKindFilter').dispatchEvent(new dom.window.Event('change'));
    assert.equal(el('agendaList').children.length,1);
    el('agendaList').querySelector('button').click();
    assert.equal(el('agendaStart').value,'2026-10-26T14:00');
    el('agendaTitle').value='Corrected characters';
    state.rpcErrors.save_game_agenda='Offline';
    const submit=()=>el('agendaForm').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
    submit();await waitFor(()=>!el('agendaSave').disabled);
    assert.equal(el('agendaForm').hidden,false);assert.equal(el('agendaTitle').value,'Corrected characters');
    assert.equal(state.agenda[0].title,'<b>Featured</b>');
    assert.equal(el('agendaStatus').dataset.kind,'error');
    state.rpcErrors.save_game_agenda=null;
    submit();await waitFor(()=>el('agendaForm').hidden);
    const call=state.rpcCalls.filter(call=>call.name==='save_game_agenda').at(-1);
    assert.equal(Object.hasOwn(call.payload,'p_profile_id'),false,'Calendar mutations have no personal actor');
    assert.equal(call.payload.p_entry.starts_at,'2026-10-26T17:00:00.000Z');
    assert.equal(call.payload.p_id,10);
    selectProfile('demo');await displayGameAgenda();
    assert.match(el('agendaList').textContent,/Corrected characters/);
    el('agendaAdd').click();el('agendaTitle').value='Unsaved draft';
    await displayGameAgenda();
    assert.equal(el('agendaTitle').value,'Unsaved draft','Reading the agenda preserves the open editor');
    el('agendaStart').value='2026-10-27T14:00';el('agendaEnd').value='2026-10-26T14:00';
    const writes=state.rpcCalls.filter(call=>call.name==='save_game_agenda').length;
    submit();await waitFor(()=>!el('agendaSave').disabled);
    assert.equal(state.rpcCalls.filter(call=>call.name==='save_game_agenda').length,writes,'Invalid periods never reach the database');
    assert.match(el('agendaStatus').textContent,/depois do início/);
    el('agendaCancel').click();
    const {default:Swal}=await import('../js/vendor/sweetalert2/sweetalert2.esm.min.js');
    let approved=false;
    t.mock.method(Swal,'fire',async options=>{
        assert.equal(options.showCancelButton,true);
        assert.match(options.text,/todos os perfis/);
        return {isConfirmed:approved};
    });
    const remove=()=>el('agendaList').querySelector('[data-id="10"]').querySelectorAll('button')[1].click();
    remove();await new Promise(resolve=>setImmediate(resolve));
    assert.equal(state.rpcCalls.filter(call=>call.name==='delete_game_agenda').length,0,'Cancelling never deletes');
    approved=true;state.rpcErrors.delete_game_agenda='Offline';
    remove();await waitFor(()=>!el('agendaAdd').disabled);
    assert.ok(el('agendaList').querySelector('[data-id="10"]'),'A failed deletion keeps the visible record');
    state.rpcErrors.delete_game_agenda=null;
    remove();await waitFor(()=>!el('agendaList').querySelector('[data-id="10"]'));
    assert.equal(state.agenda.some(entry=>entry.id===10),false);
});
